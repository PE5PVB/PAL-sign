S.append(table([
    ["Bit", "Meaning"],
    ["7..6", "Always 11 (0xC0): the format marker, also a check against RS miscorrection"],
    ["5", "Text marker: 1 on the first of the 30 rows of a text cycle, else 0"],
    ["4..3", "Two bits of the text channel, see section 6"],
    ["2..0", "n = number of stereo pairs in this row, 0..4"],
], [22*mm, 148*mm]))

S.append(P("3.2 Samples: core and refinement", h2))
S.append(P("Each sample is 14 bit two's complement (the ADC's 16 bit sample arithmetically shifted right by 2). "
           "The 8 sample slots of a row are, in order, L0 R0 L1 R1 L2 R2 L3 R3; slots beyond n are zero. "
           "Sample s (taken as a 14 bit unsigned pattern, s &amp; 0x3FFF) is split into"))
S.append(B("core byte = (s &gt;&gt; 6) &amp; 0xFF, the top 8 bits (bit 13, the sign, is the MSB of the core byte);"))
S.append(B("refinement = s &amp; 0x3F, the low 6 bits."))
S.append(P("Core bytes C0..C7 follow the slot order. The 8 refinements are packed MSB first into a 48 bit string, "
           "slot 0 first, and that string forms E0..E5 (E0 holds refinement 0 and the top 2 bits of refinement 1, "
           "and so on). Reconstruction: s = (core &lt;&lt; 6) | refinement, then sign-extend from bit 13; to 16 bit: "
           "shift left by 2."))

S.append(P("3.3 Scrambling", h2))
S.append(P("Core bytes and refinement bytes are XORed with a fixed 14 byte keystream before the parity and CRC are "
           "computed, so silence is not a long flat run. The key is the same for every row: byte i of the key "
           "scrambles Ci (i = 0..7) and byte 8 + j scrambles Ej (j = 0..5). The header and the parity bytes are "
           "not scrambled. The keystream comes from a 16 bit Fibonacci LFSR, x^16 + x^14 + x^13 + x^11 + 1, "
           "seed 0xACE1, one output bit a step (the bit shifted out), packed MSB first into bytes:"))
S.append(C("lfsr = 0xACE1\n"
           "for each key byte:  k = 0\n"
           "    repeat 8 times:  bit = lfsr & 1;  lfsr = (lfsr >> 1) ^ (bit ? 0xB400 : 0);  k = (k << 1) | bit\n"
           "    key byte = k\n"
           "\n"
           "KEY = 87 23 46 DC B0 DD EE F8  FD C3 5C BF 5C 53   (hex, bytes 0..13)"))
S.append(P("A decoder can simply use the 14 constant bytes."))

S.append(P("4. Reed-Solomon code RS(13,9)", h1))
S.append(P("Field: GF(256) with the primitive polynomial x^8 + x^4 + x^3 + x^2 + 1 (0x11D), primitive element "
           "alpha = 2. Generator polynomial with roots alpha^0 .. alpha^3:"))
S.append(C("g(x) = (x - 1)(x - a)(x - a^2)(x - a^3) = x^4 + 15 x^3 + 54 x^2 + 120 x + 64   (coefficients in GF(256))"))
S.append(P("The codeword is systematic. Message m(x) = H x^8 + C0 x^7 + ... + C7 (9 bytes, header first, highest "
           "degree first); the parity is the remainder of m(x) x^4 divided by g(x); the transmitted codeword is "
           "c(x) = m(x) x^4 + parity, 13 bytes, coefficient of x^12 (the header) first, P3 = coefficient of x^0 last. "
           "Encoder as a shift register:"))
S.append(C("rem[0..3] = 0\n"
           "for each message byte d (H, then C0..C7, scrambled):\n"
           "    fb = d ^ rem[0];  rem = rem[1], rem[2], rem[3], 0\n"
           "    if fb != 0: for j in 0..3: rem[j] ^= gmul(g[j+1], fb)      # g = [1, 15, 54, 120, 64]\n"
           "P0..P3 = rem[0..3]"))
S.append(P("Syndromes S_i = c(alpha^i), i = 0..3, evaluated over the 13 bytes highest degree first (Horner). "
           "All four zero means a clean codeword. The code corrects any 2 byte errors, or up to 4 erasures "
           "(byte positions known to be doubtful), or 1 error plus 2 erasures. Because the code is tiny, the "
           "reference decoder works by trial rather than Berlekamp-Massey: for every candidate set of error "
           "positions (the erasures plus 0, 1 or 2 further positions, 78 pairs at most) solve the Vandermonde "
           "system S_i = sum_j Y_j X_j^i for the magnitudes Y_j by Gaussian elimination over GF(256), with "
           "X_j = alpha^(12 - p_j) for byte position p_j (0 = header); the first set for which all four "
           "equations agree gives the correction. Any standard RS decoder with these parameters works too. "
           "After decoding, check that bits 7..6 of the header are 11 and n is at most 4; otherwise treat the "
           "row as lost (with three or more errors the code occasionally miscorrects; the reference measured "
           "3 in 20000 such rows passing that check)."))

S.append(P("5. CRC-8 of the refinement", h1))
S.append(P("Polynomial x^8 + x^2 + x + 1 (0x07), initial value 0, no reflection, no final XOR, over the 6 "
           "scrambled refinement bytes E0..E5 in order (the plain CRC-8/ATM style):"))
S.append(C("c = 0\n"
           "for each byte d: c ^= d; repeat 8 times: c = (c & 0x80) ? ((c << 1) ^ 0x07) & 0xFF : (c << 1) & 0xFF"))
S.append(P("If the CRC does not match, discard the refinement and play the row from the core bytes alone "
           "(refinement = 0, or 32 for a mid-tread guess): 8 bit audio for that row, no hole. The CRC passes "
           "a damaged refinement 1 time in 256, which costs at most a small click."))

S.append(P("6. Text channel", h1))
S.append(P("Header bits 5..3 carry a 10 character text, 6 bits a character, 60 bits, sent 2 bits a row over 30 "
           "consecutive rows (in the generator's row order, field by field) and then repeated; a cycle takes "
           "about 2 ms. Bit 5 of the header is 1 on the first row of a cycle only. The 60 bit string is the 10 "
           "characters MSB first, and bits 4..3 of row k of the cycle (k = 0..29) are bits 59 - 2k and 58 - 2k of "
           "that string. Characters index this 64 symbol alphabet (index 0 = space):"))
S.append(C(' ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.,-/:;!?\'()+=&@#*%<>"_[]{}|'))
S.append(P("Decoding: on a header with bit 5 set start a new cycle; collect bits 4..3 of it and of the 29 rows "
           "that follow; if any row in between is lost, drop the cycle and wait for the next marker. Trailing "
           "spaces are padding. The text sits inside the RS codeword, so it is as protected as the audio."))

