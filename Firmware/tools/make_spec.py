    ["8..11", "Guard", "4 bits of 0: lets the video filter settle before the sync byte"],
    ["12..19", "Sync", "0x2E = 00101110"],
    ["20..123", "Core codeword", "13 bytes, RS(13,9): header, 8 core bytes (scrambled), 4 parity bytes"],
    ["124..171", "Refinement", "6 bytes (scrambled): the low 6 bits of the 8 samples, 48 bits"],
