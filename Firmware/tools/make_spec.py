    "demands 40 levels), either polarity. Keep the threshold.",
    "Find the sync byte: 4 low guard bits followed by 0x2E, allowing at most one wrong bit, searching a few "
    "pixels either way of the nominal position (run-in start + 12 bits) and a small period correction. "
    "Capture cards regenerate their own pixel clock; the reference measures the nominal period steadily but "
    "searches 3.4 .. 4.6.",
    "Slice the 160 bits after the sync byte at the bit centres into 20 bytes. Optionally remember, per byte, "
    "how close its bits came to the threshold: the bytes with the smallest margin are the erasure candidates.",
    "Decode the 13 byte core codeword (errors only; if that fails and there are clearly doubtful bytes, "
    "retry with the two, then four, weakest as erasures). Check header bits 7..6 = 11 and n <= 4.",
    "Unscramble C0..C7 with key bytes 0..7. Check the CRC of E0..E5; if good, unscramble them with key bytes "
    "8..13 and unpack the 6 bit refinements, else use zero refinements.",
    "Rebuild the n pairs (L, R) as 14 bit two's complement, shift to 16 bit, and append them to the audio stream "
    "in field order. Feed the text channel from the header.",
    "A row whose core cannot be decoded is a hole of about 3 pairs: interpolate linearly from the last good "
