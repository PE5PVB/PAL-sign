ORDER = " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789:!?/@#*_+<>-.,=()" + OSLASH


def bits(art, ch):
    rows = art.strip(NL).split(NL)
    assert len(rows) == ROWS, "%r: %d rows instead of %d" % (ch, len(rows), ROWS)
    out = []
    for r in rows:
        assert len(r) == COLS, "%r: row %r is %d wide instead of %d" % (ch, r, len(r), COLS)
        v = 0
        for c, p in enumerate(r):
            assert p in ".#", "%r: unknown character %r" % (ch, p)
            if p == "#":
                assert not (ch in NARROW and c >= 3), "%r is narrow but draws in column %d" % (ch, c)
                v |= 1 << (COLS - 1 - c)
        out.append(v)
    return out


def main():
    for ch in ORDER:
        assert ch in G, "character picture missing for %r" % ch
    lines = []
    for ch in ORDER:
        b = bits(G[ch], ch)
        name = "GLYPH_OSLASH" if ch == OSLASH else "'%s'" % ch
        lines.append("    {%s, {%s}}," % (name, ", ".join("0x%02X" % v for v in b)))

    with io.open(OUT, "w", encoding="utf-8", newline=NL) as fh:
        fh.write("""// GENERATED by tools/make_font.py -- do not edit by hand.
//
// %dx%d character set, traced from a photograph of a broadcast PM5544
// (NOZEMA / NEDERLAND 2). See the comments in make_font.py for the
// measurement the dimensions come from.
#pragma once

#include <stdint.h>

// Internal one byte code for the O with a slash through it: in UTF-8
// that character is two bytes and so does not fit in a char literal.
#define GLYPH_OSLASH '%s'

struct Glyph {
  char c;
  uint8_t r[%d];  // %d bits per row, bit %d = leftmost column
};

// Punctuation that uses only the first 3 columns; textPrepare
// therefore gives them only 3 columns of letter width.
#define FONT_NARROW_GLYPHS "%s"

static const Glyph FONT[] = {
%s
};
static const int FONT_COUNT = (int)(sizeof(FONT) / sizeof(FONT[0]));
""" % (COLS, ROWS, chr(92) + "x01", ROWS, COLS, COLS - 1, NARROW, NL.join(lines)))
    print("%d characters written to tools/font_pm5544.h" % len(ORDER))


if __name__ == "__main__":
    main()
