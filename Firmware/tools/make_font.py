"""
Generates the character set in tools/font_pm5544.h.

The font is traced from a photograph of a broadcast PM5544 (NOZEMA /
NEDERLAND 2). From that it turned out that the original is not a 5x7
font but much finer: 7 columns wide, 15 rows high, with strokes a
single dot thick. Characteristic are the round bulges (O, C, G, S) and
the continuous diagonal strokes in N, M, Z, A and R, all of them things
that cannot be drawn on a 5x7 grid.

Measured from the photograph and worked back to the 720x576 grid:
  character height  about 30 px
  pitch             about 18 px
  character width   about 14 px
That comes out at 2 picture pixels per grid dot, in both directions.

Ten characters stand literally in the photograph (A D E L M N O R Z 2);
the rest is drawn in in the same style.
"""

